'use strict';
/**
 * WORKLY — driver photograph / portrait system.
 *
 * Discovery uses the Wikimedia Commons API (free, licence-carrying media). Every
 * record keeps its source page, licence, licence URL, photographer and
 * attribution so images are never presented without provenance.
 *
 * Identity safety rules (from the specification):
 *   - never assume the first search hit is the right person
 *   - require the driver's family name to appear in the file title
 *   - never use generated faces
 *   - when nothing verifies, the UI renders the WORKLY placeholder
 */
const { db, nowTs } = require('./db');

const API = 'https://commons.wikimedia.org/w/api.php';
const USER_AGENT = 'WORKLY-Academic-Platform/1.0 (SMKA Shams; driver portrait research)';

async function commonsSearch(name, limit = 8) {
  const params = new URLSearchParams({
    action: 'query',
    format: 'json',
    generator: 'search',
    gsrnamespace: '6', // File:
    gsrsearch: `${name} portrait`,
    gsrlimit: String(limit),
    prop: 'imageinfo',
    iiprop: 'url|extmetadata|mime',
    iiurlwidth: '480',
  });
  const res = await fetch(`${API}?${params}`, {
    headers: { 'User-Agent': USER_AGENT, Accept: 'application/json' },
    signal: AbortSignal.timeout(20000),
  });
  if (!res.ok) throw new Error(`Wikimedia Commons responded ${res.status}`);
  const data = await res.json();
  return Object.values(data?.query?.pages || {});
}

function metaValue(extmetadata, key) {
  const v = extmetadata?.[key]?.value;
  if (v == null) return null;
  return String(v)
    .replace(/<[^>]*>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .trim();
}

function isGenerated(extmetadata, title) {
  const blob = `${title} ${metaValue(extmetadata, 'ImageDescription') || ''} ${metaValue(extmetadata, 'Categories') || ''}`.toLowerCase();
  return /(ai[- ]generated|midjourney|stable diffusion|dall[- ]?e|generated by artificial)/.test(blob);
}

/**
 * A candidate is only accepted when the driver's surname appears in the file
 * title. This is deliberately conservative: a wrong portrait is worse than a
 * placeholder.
 */
function nameMatches(title, driverName) {
  const t = title.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  const parts = driverName
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .split(/[\s.]+/)
    .filter((p) => p.length > 3);
  if (!parts.length) return false;
  const surname = parts[parts.length - 1];
  return t.includes(surname) && parts.some((p) => t.includes(p));
}

function saveCandidate(driverId, candidate, { verify }) {
  const exists = db
    .prepare('SELECT id FROM driver_images WHERE driver_id = ? AND image_url = ?')
    .get(driverId, candidate.image_url);
  if (exists) return exists.id;
  const info = db
    .prepare(
      `INSERT INTO driver_images (driver_id, source, source_page_url, image_url, thumb_url,
        license_name, license_url, photographer, attribution, verified, is_primary, created_at)
       VALUES (?,?,?,?,?,?,?,?,?,?,0,?)`,
    )
    .run(
      driverId,
      'Wikimedia Commons',
      candidate.source_page_url,
      candidate.image_url,
      candidate.thumb_url,
      candidate.license_name,
      candidate.license_url,
      candidate.photographer,
      candidate.attribution,
      verify ? 1 : 0,
      nowTs(),
    );
  return Number(info.lastInsertRowid);
}

/** Promote one image to primary, demoting any previous primary first. */
function setPrimary(driverId, imageId) {
  return db.transaction(() => {
    db.prepare('UPDATE driver_images SET is_primary = 0 WHERE driver_id = ?').run(driverId);
    db.prepare('UPDATE driver_images SET is_primary = 1, verified = 1 WHERE id = ? AND driver_id = ?').run(
      imageId,
      driverId,
    );
    return db.prepare('SELECT * FROM driver_images WHERE id = ?').get(imageId);
  })();
}

/**
 * Discover portraits for one driver. Returns a summary of what was stored.
 * Network failure is reported, never treated as "no photo exists".
 */
async function discoverForDriver(driverId, { limit = 8, autoPrimary = true } = {}) {
  const driver = db.prepare('SELECT * FROM drivers WHERE id = ?').get(driverId);
  if (!driver) throw Object.assign(new Error('Driver not found'), { status: 404 });

  let pages;
  try {
    pages = await commonsSearch(driver.full_name || driver.name, limit);
  } catch (err) {
    return { driverId, ok: false, error: err.message, stored: 0, verified: 0 };
  }

  let stored = 0;
  let verified = 0;
  const accepted = [];
  for (const page of pages) {
    const info = page.imageinfo?.[0];
    if (!info) continue;
    const mime = info.mime || '';
    if (!/^image\/(jpeg|png|webp)/.test(mime)) continue;
    const meta = info.extmetadata || {};
    if (isGenerated(meta, page.title)) continue;

    const match = nameMatches(page.title, driver.name);
    const candidate = {
      source_page_url: `https://commons.wikimedia.org/wiki/${encodeURIComponent(page.title.replace(/ /g, '_'))}`,
      image_url: info.url,
      thumb_url: info.thumburl || info.url,
      license_name: metaValue(meta, 'LicenseShortName'),
      license_url: metaValue(meta, 'LicenseUrl'),
      photographer: metaValue(meta, 'Artist'),
      attribution: metaValue(meta, 'AttributionRequired') === 'true'
        ? `${metaValue(meta, 'Artist') || 'Unknown'} / ${metaValue(meta, 'LicenseShortName') || 'see source'}`
        : metaValue(meta, 'Credit'),
    };
    const id = saveCandidate(driverId, candidate, { verify: match });
    stored += 1;
    if (match) {
      verified += 1;
      accepted.push(id);
    }
  }

  let primary = null;
  if (autoPrimary && accepted.length) {
    const current = db
      .prepare('SELECT id FROM driver_images WHERE driver_id = ? AND is_primary = 1')
      .get(driverId);
    if (!current) primary = setPrimary(driverId, accepted[0]);
  }
  return { driverId, ok: true, stored, verified, primary };
}

/** Batch discovery with a small delay to stay polite to the API. */
async function discoverForDrivers(driverIds, { delayMs = 250, onProgress } = {}) {
  const results = [];
  for (const id of driverIds) {
    const r = await discoverForDriver(id);
    results.push(r);
    if (onProgress) onProgress(r);
    await new Promise((resolve) => setTimeout(resolve, delayMs));
  }
  return {
    attempted: driverIds.length,
    withVerifiedPortrait: results.filter((r) => r.verified > 0).length,
    failed: results.filter((r) => r.ok === false).length,
    results,
  };
}

function primaryImage(driverId) {
  return db
    .prepare('SELECT * FROM driver_images WHERE driver_id = ? AND is_primary = 1')
    .get(driverId);
}

function imagesFor(driverId) {
  return db
    .prepare('SELECT * FROM driver_images WHERE driver_id = ? ORDER BY is_primary DESC, id ASC')
    .all(driverId);
}

module.exports = {
  commonsSearch,
  discoverForDriver,
  discoverForDrivers,
  setPrimary,
  primaryImage,
  imagesFor,
  nameMatches,
};
